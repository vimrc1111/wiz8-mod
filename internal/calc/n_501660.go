package calc

// Node 0x501660: may the queued item spell of one character be executed.
// The original reads the queue record, the item instance it points at, the
// character, item and spell records and delegates to 0x522a30 (item use),
// 0x51d800 (item activation), 0x537220 (target, context 4) and the spell
// context test 0x5001e0. This calc rebuilds the same memory the emulator case
// writes (qimSetup, then every input in order, as emu.py does) and hands each
// callee calc the vector its own case would have read from that memory.
//
// Fixture caps (panic past them): character slot 0..7, item index 0..3 (the
// items array has 4 records), instance positions 8 / 12 / 12 for queue kinds
// 0 / 1 / 2 (the original accepts up to 500 for kind 2, 0x5221fa), spell
// below 0x96 and spell context below 5 (0x5001e0 asserts), reads outside the
// arena that no input or setup wrote. Queue kinds above 2 assert (0x5221a9).
// 0x537220 is modelled with the globals 0x68ec78, 0x683f95, 0x683f96, 0x683fe7
// and the selected-character global zero (panic otherwise), and only for
// spell ids 0..9, 88 and 119; the vectors inherit its other caps and those of
// 0x522a30 and 0x51d800. Spell usability is the separate qimSpellUsable
// (0x5001e0 with argument 0) because no calc models that function.

const (
	qimArena = 0x20000000
	qimWho   = 0
	qimItem  = 354 // scratch cells: the instance fields are written through also
)

type qimField struct {
	addr, stride, count int64
	size                int
	signed              bool
	idx                 int
	ws                  int64
	also                []qimField
}

type qimRef struct {
	m int
	s bool
}

type qimRun struct {
	mem map[int64]byte
	row []int64
	who int64
	p   int64
}

func (q *qimRun) read(a int64, size int, signed bool) int64 {
	var u uint64
	for k := size - 1; k >= 0; k-- {
		b, ok := q.mem[a+int64(k)]
		if !ok && (a+int64(k) < qimArena || a+int64(k) >= qimArena+0x100000) {
			panic("queued item magic: read outside the fixture")
		}
		u = u<<8 | uint64(b)
	}
	v := int64(u)
	if signed {
		s := uint(64 - 8*size)
		v = v << s >> s
	}
	return v
}

func (q *qimRun) write(a int64, size int, signed bool, v int64) {
	lo, hi := int64(0), int64(1)<<(8*uint(size))-1
	if signed {
		lo, hi = -(hi+1)/2, hi/2
	}
	if v < lo || v > hi {
		panic("queued item magic: value does not fit its field")
	}
	for k := 0; k < size; k++ {
		q.mem[a+int64(k)] = byte(uint64(v) >> (8 * uint(k)))
	}
}

func (q *qimRun) put(f qimField, v int64) {
	a := f.addr
	if f.idx >= 0 {
		k := q.row[f.idx]
		if k < 0 {
			return
		}
		if k >= f.count {
			panic("queued item magic: index outside the field's count")
		}
		a += k * f.stride
	}
	q.write(a, f.size, f.signed, v)
}

// at is where the original code reads field f: the index is the value now in
// memory. A negative index means no record: the callee calcs treat the field as
// unwritten (zero), exactly as the case writer skips the write.
func (q *qimRun) at(f qimField) (int64, bool) {
	a := f.addr + q.who*f.ws
	if f.idx >= 0 {
		k := q.val(f.idx, qimFields[f.idx].signed)
		if k < 0 {
			return 0, false
		}
		a += k * f.stride
	}
	return a, true
}

func (q *qimRun) val(i int, signed bool) int64 {
	switch i {
	case qimWho:
		return q.who
	case qimItem:
		return q.read(q.p, 4, true)
	}
	a, ok := q.at(qimFields[i])
	if !ok {
		return 0
	}
	return q.read(a, qimFields[i].size, signed)
}

// vec fills one callee's input vector from memory; negative refs are the
// values 0x501660 passes itself.
func (q *qimRun) vec(refs []qimRef, spell int64) []int64 {
	v := make([]int64, len(refs))
	for j, r := range refs {
		switch r.m {
		case -1:
			v[j] = q.who
		case -2:
			v[j] = q.read(q.p, 4, true)
		case -3:
			v[j] = q.p
		case -4:
			v[j] = q.read(q.p+6, 1, false)
		case -5:
			v[j] = q.read(q.p+5, 1, false)
		case -6:
			v[j] = q.read(0x685174, 4, false) + q.who*6242
		case -7:
			v[j] = spell
		case -8:
			v[j] = 4
		case -9: // item entries pointer of 0x537220: only its being nonzero is read (n_5199f0.go)
			v[j] = 0x20013498
		default:
			v[j] = q.val(r.m, r.s)
		}
	}
	return v
}

// vecB is the vector of 0x537220. Its item spells are inputs for all four items
// but only the selected item's is read (n_537220.go), so the others stay zero.
func (q *qimRun) vecB(spell, sel int64) []int64 {
	for _, i := range []int{147, 152, 154, 155, 156} { // combatPhase, selectedCharacterSlot, specialSpellMode, specialItemMode, combatState
		if q.val(i, false) != 0 {
			panic("queued item magic: 0x537220 is modelled with the special-mode globals zero")
		}
	}
	v := q.vec(qimBRefs, spell)
	for k := int64(0); k < 4; k++ {
		if k != sel {
			v[17+k] = 0 // item0Spell..item3Spell.
		}
	}
	return v
}

// qimInstance is 0x522180: the address of the instance record for queue kind
// cd and position ce.
func qimInstance(chars, who, cd, ce int64) int64 {
	switch cd {
	case 0:
		if ce >= 8 {
			panic("queued item magic: instance position outside the fixture")
		}
		return chars + who*6242 + 0x1029 + ce*12
	case 1:
		if ce >= 12 {
			panic("queued item magic: instance position outside the fixture")
		}
		return chars + who*6242 + 0xf5d + ce*12
	case 2:
		if ce >= 12 {
			panic("queued item magic: instance position outside the fixture")
		}
		return 0x685191 + ce*12
	}
	panic("queued item magic: queue kind above 2 asserts")
}

// qimSpellUsable is 0x5001e0 with its second argument 0.
func (q *qimRun) qimSpellUsable(spell, spells int64) bool {
	if spell >= 0x96 {
		panic("queued item magic: spell outside the spell table (0x5001e0 asserts)")
	}
	ctx := q.read(spells+spell*447+0x13b, 4, true)
	if ctx < 0 || ctx > 4 {
		panic("queued item magic: spell context outside 0..4 (0x5001e0 asserts)")
	}
	combat, lock := q.read(0x683f94, 1, false), q.read(0x683f9b, 1, false)
	cm, cx := q.read(0x683f9c, 1, false), q.read(0x683f9d, 1, false)
	if q.read(0x68ec78, 4, false) == 6 && combat == 0 && lock != 0 && (spell == 0x17 || spell == 0x3a) {
		return true
	}
	anyFlag := cm != 0 || cx != 0
	switch ctx {
	case 0:
		return lock == 0 && !anyFlag
	case 1:
		return combat == 1 && lock == 0 && !anyFlag
	case 2:
		return combat == 0 && lock == 0 && !anyFlag
	case 3:
		return lock != 0 && !anyFlag
	}
	switch spell {
	case 0x27:
		return anyFlag
	case 0x12:
		return cx != 0
	}
	return false
}

func queuedItemMagicEligibilityNode(in []int64, r Rand) []int64 {
	if len(in) != len(qimFields) {
		panic("queued item magic: wrong input count")
	}
	if in[qimWho] < 0 || in[qimWho] > 7 {
		panic("queued item magic: character slot outside 0..7")
	}
	q := &qimRun{mem: map[int64]byte{}, row: in, who: in[qimWho]}
	for i := 0; i < len(qimSetup); i += 3 {
		q.write(qimSetup[i], int(qimSetup[i+1]), false, qimSetup[i+2])
	}
	for i, f := range qimFields {
		if f.addr < 0 {
			continue
		}
		q.put(f, in[i])
		for _, t := range f.also {
			q.put(t, in[i])
		}
	}
	rec := q.read(0x685178, 4, false) + q.who*262
	exit := func() []int64 { return []int64{0, q.read(rec+0xa5, 4, false)} }
	cd := q.read(rec+0xcd, 1, false)
	if cd >= 0x80 { // 0x501685.
		return exit()
	}
	ce := q.read(rec+0xce, 2, false)
	if ce >= 0x8000 { // 0x501697.
		return exit()
	}
	q.p = qimInstance(q.read(0x685174, 4, false), q.who, cd, ce)
	q.write(rec+0xa5, 4, false, q.p)                // 0x5016b2.
	if cd == 2 && q.read(0x683f94, 1, false) != 0 { // 0x5016c1.
		return exit()
	}
	idx := q.read(q.p, 4, false)
	if idx == 0xffffffff || idx != q.read(rec+0xc9, 4, false) { // 0x5016d1, 0x5016e0.
		return exit()
	}
	if idx > 3 || idx >= q.read(0x683f78, 4, false) {
		panic("queued item magic: item index outside the fixture or the definition count")
	}
	if itemUseEligibilityNode(q.vec(qimARefs, 0), r)[0] == 0 { // 0x522a30.
		return exit()
	}
	if itemActivationAllowedNode(q.vec(qimCRefs, 0), r)[0] == 0 { // 0x51d800.
		return exit()
	}
	item := q.read(0x68516c, 4, false) + idx*269
	spell := q.read(item+0x63, 1, false) // 0x520880.
	typ := q.read(item+0x3e, 1, false)   // 0x5207c0 is 1 for types 0x10, 0x15, 0x16.
	selfUse := typ == 0x10 || typ == 0x15 || typ == 0x16
	spells := q.read(0x65be1c, 4, false)
	kind := q.read(spells+spell*447+0x137, 4, false) // 0x4ac9d0.
	if kind == 1 && selfUse {
		kind = 0
	}
	if kind == 0 && q.read(rec+0xad, 4, false) != q.who { // 0x501751.
		return exit()
	}
	if !q.qimSpellUsable(spell, spells) {
		return exit()
	}
	if q.read(0x683f94, 1, false) == 0 && actionTargetEligibleNode(q.vecB(spell, idx), r)[0] == 0 { // 0x537220.
		return exit()
	}
	return []int64{1, q.read(rec+0xa5, 4, false)}
}

