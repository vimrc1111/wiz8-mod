func npcRegionPenaltyResetNode(in []int64, r Rand) []int64 {
	if len(in) != 1100 {
		panic("NPC reset: invalid input count")
	}
	active := [2]int{1087, 1090}
	hitPoints := [2]int{1088, 1091}
	indices := [2]int{1089, 1092}
	unavailable := [2]int{1095, 1097}
	penalties := [2]int64{in[1096], in[1098]}
	enabled := [2]int64{in[1], in[2]}
	out := make([]int64, 0, 520)
	for slot := 0; slot < 2; slot++ {
		previous := make([]int64, 257) // 103 status + 103 total + 48 abilities + 3 load fields; 0x50e650 interface.
		for i, index := range npcResetOldMap[slot] {
			previous[i] = in[index]
		}
		if in[active[slot]] != 0 && uint32(in[hitPoints[slot]]) != 0 {
			if in[1093] != 0x20030000 {
				panic("NPC reset: missing NPC list")
			} // case arena list.
			index := int32(in[indices[slot]])
			// 0x50db9a: a signed out-of-range index falls back to entry zero.
			if index >= int32(in[1094]) {
				index = 0
			}
			if index < 0 || index > 1 || in[unavailable[index]] != 0 {
				panic("NPC reset: invalid NPC reference")
			}
			penalties[index], enabled[slot] = 0, 0 // NPC+0xe8 and side-record+0xfe, 0x50dbb5..0x50dbbc.
			rebuild := make([]int64, 348)
			rebuild[0] = int64(slot)
			for i := 1; i < 348; i++ {
				rebuild[i] = in[npcResetRebuildMap[slot][i]]
			}
			rebuild[2], rebuild[3] = enabled[0], enabled[1]
			previous = statusEffectRebuildNode(rebuild, r)
		}
		out = append(out, previous...)
	}
	return append(out, enabled[0], penalties[0], enabled[1], penalties[1], in[1099], 1)
}
