// nextPhase is 0x4eb7f0 monster_next_attack_phase(m); the rest of the cycle
// group lives in n_523c00.go.
func (w *mcaWorld) nextPhase(m uint32) {
	w.template(m)
	w.fatigue(m, w.cost(m))
	w.stub(0x4c6200, w.u32(m+0xc), 1)
	w.put(w.u32(0x6836a8)+0x7b0, 4, 0)
	w.put(w.u32(0x6836a8)+0x7b8, 4, 0)
	t := w.u32(m + 0x10)
	if w.u8(t+4) == 0 {
		return
	}
	if w.u32(m+0x2e1) != 0 || w.u32(t+9) == 0 || !w.pick(m) {
		w.put(t, 4, 0)
		return
	}
	d := w.u32(t+9) + 1
	if d == 0 {
		panic("monster next attack phase: divisor wraps to 0 (0x4eb883)")
	}
	v := w.u32(t) + (100-w.u32(w.u32(0x6836a8)+8))/d // 0x4eb879: unsigned
	w.put(t, 4, uint64(v))
	if v > 100 {
		w.put(t, 4, 0)
		return
	}
	w.round(t)
}

func mcaPhaseBody(w *mcaWorld) { w.nextPhase(mcaArg(w, 0)) }

func monsterNextAttackPhaseNode(in []int64, r Rand) []int64 {
	return mcaRun(&mcaSpecPhase, true, mcaPhaseBody)(in, r)
}

func mcaEmuPhase(in []int64, r Rand) []int64 {
	return mcaRun(&mcaSpecPhase, false, mcaPhaseBody)(in, r)
}

